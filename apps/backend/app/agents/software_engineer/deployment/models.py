"""Data models for the Enterprise Software Deployment Engine.
"""

from datetime import datetime
from typing import Any, Dict, List, Optional
from pydantic import BaseModel, Field

class DeploymentRequest(BaseModel):
    """Configuration guidelines request for a deployment job."""
    project_path: str = Field(..., description="Path to the repository/project root.")
    environment: str = Field("production", description="Target environment (development, testing, production).")
    variables: Dict[str, str] = Field(default_factory=dict, description="Configuration environment variables.")
    target_platform: str = Field("docker", description="Deployment target platform (docker, kubernetes, helm).")
    model_override: Optional[str] = Field(None, description="Local model override name.")

class EnvironmentInfo(BaseModel):
    """Detected language, runtime, and ecosystem requirements of the project."""
    language: str = Field(..., description="Detected programming language (Python, Node.js, Java, Go, Rust).")
    framework: Optional[str] = Field(None, description="Detected application framework (FastAPI, React, Spring Boot, etc.).")
    runtime_version: Optional[str] = Field(None, description="Runtime engine version.")
    package_manager: Optional[str] = Field(None, description="Package manager used (pip, npm, yarn, cargo, etc.).")
    database: Optional[str] = Field(None, description="Detected database (PostgreSQL, SQLite, MySQL, Redis, MongoDB, etc.).")
    env_vars: List[str] = Field(default_factory=list, description="Required environment variable names.")
    required_services: List[str] = Field(default_factory=list, description="Third-party service dependencies (e.g. redis, postgres).")
    docker_files: List[str] = Field(default_factory=list, description="Detected docker files.")

class BuildResult(BaseModel):
    """The outcome of compilation, test checks, and packaging validation."""
    success: bool = Field(..., description="True if code compiled and verified successfully.")
    duration: float = Field(0.0, description="Time spent validating build.")
    artifacts: List[str] = Field(default_factory=list, description="List of local files generated by build.")
    errors: List[str] = Field(default_factory=list, description="Error messages encountered during validation.")

class DockerConfiguration(BaseModel):
    """Containerization settings."""
    dockerfile_content: str = Field(..., description="Generated Dockerfile.")
    compose_content: str = Field(..., description="Generated docker-compose.yml.")
    base_image: str = Field(..., description="Calculated secure base image.")
    ports: List[int] = Field(default_factory=list, description="Exposed application ports.")

class PipelineConfiguration(BaseModel):
    """Configurations generated for CI/CD engines."""
    github_actions_yaml: Optional[str] = Field(None, description="GitHub actions workflow config.")
    gitlab_ci_yaml: Optional[str] = Field(None, description="GitLab CI config.")
    jenkinsfile_content: Optional[str] = Field(None, description="Jenkinsfile pipeline script.")

class DeploymentArtifact(BaseModel):
    """Represents a generated configuration artifact package."""
    name: str = Field(..., description="Artifact name/filename.")
    type: str = Field(..., description="Artifact type (dockerfile, compose, kubernetes, pipeline, report).")
    path: str = Field(..., description="Physical storage path of the artifact.")
    checksum: str = Field(..., description="SHA-256 integrity checksum.")

class ReleaseVersion(BaseModel):
    """Deployment version details."""
    version: str = Field(..., description="Semantic version string.")
    git_commit: Optional[str] = Field(None, description="Current Git commit hash.")
    timestamp: datetime = Field(default_factory=datetime.utcnow, description="Release generation timestamp.")
    changelog: str = Field(..., description="Automatically drafted release notes.")

class RollbackPlan(BaseModel):
    """Plan details to revert a failed release."""
    target_version: str = Field(..., description="Version to rollback to.")
    steps: List[str] = Field(default_factory=list, description="Execution steps to run rollback (e.g. helm rollback, db migrations).")
    rollback_script: str = Field(..., description="Shell script/commands for rollback execution.")

class HealthCheck(BaseModel):
    """Defines target configurations for service health check rules."""
    endpoint: str = Field("/health", description="Target health path or endpoint.")
    status: str = Field("untested", description="Health check diagnostic status.")
    latency: float = Field(0.0, description="Response time in milliseconds.")
    rules: Dict[str, Any] = Field(default_factory=dict, description="Custom validation expectations.")

class DeploymentPlan(BaseModel):
    """Ordered steps to complete deployment preparation."""
    stages: List[str] = Field(default_factory=list, description="List of pipeline stages planned.")
    created_at: datetime = Field(default_factory=datetime.utcnow, description="Plan creation timestamp.")
    status: str = Field("pending", description="Plan execution status.")

class DeploymentReport(BaseModel):
    """Consolidated summary reporting the output of the whole engine workflow."""
    status: str = Field(..., description="Result status (success, warning, failed).")
    environment_info: EnvironmentInfo = Field(..., description="Source environment profile details.")
    build_result: BuildResult = Field(..., description="Local build status.")
    container_config: DockerConfiguration = Field(..., description="Dockerfile and compose content details.")
    pipeline_config: PipelineConfiguration = Field(..., description="Generated CI pipelines.")
    release_version: ReleaseVersion = Field(..., description="Release version info.")
    rollback_plan: RollbackPlan = Field(..., description="Calculated rollback instructions.")
    artifacts: List[DeploymentArtifact] = Field(default_factory=list, description="Generated config file templates.")
    validation_status: str = Field("passed", description="Status of static and syntax checks.")
    report_markdown: str = Field("", description="Detailed printable markdown implementation summary.")
