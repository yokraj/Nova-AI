"""Pydantic data models, enums, and structures for AI OS Kernel.
"""

from enum import Enum
from typing import Any, Dict, List, Optional
from pydantic import BaseModel, Field
import time
import uuid


class OperatingMode(str, Enum):
    """Enumerate kernel operating modes."""

    VOICE = "VOICE"
    TEXT = "TEXT"
    SILENT = "SILENT"
    AUTONOMOUS = "AUTONOMOUS"
    ASSISTED = "ASSISTED"
    DEBUG = "DEBUG"
    COPILOT = "COPILOT"


class PriorityLevel(str, Enum):
    """Enumerate task priority levels."""

    CRITICAL = "CRITICAL"
    HIGH = "HIGH"
    NORMAL = "NORMAL"
    LOW = "LOW"
    BACKGROUND = "BACKGROUND"


class KernelState(str, Enum):
    """Enumerate state of AI OS Kernel."""

    UNINITIALIZED = "UNINITIALIZED"
    IDLE = "IDLE"
    PROCESSING = "PROCESSING"
    PLANNING = "PLANNING"
    EXECUTING = "EXECUTING"
    VERIFYING = "VERIFYING"
    PAUSED = "PAUSED"
    ERROR = "ERROR"
    SHUTDOWN = "SHUTDOWN"


class IntentRequest(BaseModel):
    """Structured request sent to Universal Intent Engine."""

    request_id: str = Field(default_factory=lambda: f"req_{uuid.uuid4().hex[:8]}")
    query: str = Field(..., description="Natural language input query")
    operating_mode: OperatingMode = Field(OperatingMode.VOICE, description="Target operating mode")
    priority: PriorityLevel = Field(PriorityLevel.NORMAL, description="Execution priority")
    user_id: str = Field("user_default", description="Requesting user ID")
    session_id: str = Field("sess_default", description="Active session ID")
    source: str = Field("voice", description="Input source (voice, desktop_ui, api, web)")
    parameters: Dict[str, Any] = Field(default_factory=dict, description="Input parameters")
    metadata: Dict[str, Any] = Field(default_factory=dict, description="Additional request metadata")
    timestamp: float = Field(default_factory=time.time, description="Creation Unix timestamp")


class CapabilityMatch(BaseModel):
    """Capabilities resolved across all AI subsystems for an intent."""

    agents: List[str] = Field(default_factory=list, description="Required AI agents")
    plugins: List[str] = Field(default_factory=list, description="Required plugins")
    services: List[str] = Field(default_factory=list, description="Required system services")
    automation_modules: List[str] = Field(default_factory=list, description="Required automation modules")
    browser_actions: List[str] = Field(default_factory=list, description="Required browser actions")
    desktop_actions: List[str] = Field(default_factory=list, description="Required desktop actions")
    memory_stores: List[str] = Field(default_factory=list, description="Required memory stores")
    models: List[str] = Field(default_factory=list, description="Required LLM/multimodal models")
    execution_runtime: str = Field("local_async", description="Matched execution runtime")


class PlanNode(BaseModel):
    """Single node in dynamic execution DAG."""

    node_id: str = Field(default_factory=lambda: f"node_{uuid.uuid4().hex[:8]}")
    title: str = Field(..., description="Step title or description")
    action_type: str = Field(..., description="Action category (agent, plugin, automation, code, voice, service)")
    subsystem: str = Field(..., description="Target subsystem name")
    parameters: Dict[str, Any] = Field(default_factory=dict, description="Step parameters")
    dependencies: List[str] = Field(default_factory=list, description="IDs of dependent nodes")
    requires_approval: bool = Field(False, description="True if step requires security approval")
    verification_check: Optional[str] = Field(None, description="Expected post-condition check")
    status: str = Field("pending", description="Execution status (pending, executing, completed, failed, skipped)")
    output: Optional[Any] = Field(None, description="Output returned by node execution")


class ExecutionPlan(BaseModel):
    """Dynamic DAG execution plan generated by planner."""

    plan_id: str = Field(default_factory=lambda: f"plan_{uuid.uuid4().hex[:8]}")
    goal: str = Field(..., description="Structured goal name")
    intent_type: str = Field("general", description="Categorized intent type")
    nodes: List[PlanNode] = Field(default_factory=list, description="DAG nodes")
    waves: List[List[str]] = Field(default_factory=list, description="Parallel execution node ID waves")
    fallback_nodes: Dict[str, str] = Field(default_factory=dict, description="Fallback node mappings")
    retry_policy: Dict[str, Any] = Field(default_factory=lambda: {"max_retries": 3, "backoff": 1.5})
    approval_checkpoints: List[str] = Field(default_factory=list, description="Node IDs requiring approval")
    verification_steps: List[str] = Field(default_factory=list, description="Node IDs with verifications")
    status: str = Field("created", description="Plan status (created, running, completed, failed, paused)")
    created_at: float = Field(default_factory=time.time)


class VerificationResult(BaseModel):
    """Universal verification audit record."""

    verified: bool = Field(..., description="True if execution verified successfully")
    status: str = Field("SUCCESS", description="Verification status code (SUCCESS, FAILED, RETRYING, ESCALATED)")
    checks_performed: List[str] = Field(default_factory=list, description="List of verification assertions")
    details: Dict[str, Any] = Field(default_factory=dict, description="Diagnostic state output")
    failure_reason: Optional[str] = Field(None, description="Reason if verification failed")
    verified_at: float = Field(default_factory=time.time)


class ExecutionContext(BaseModel):
    """Unified operating context merging all subsystem context fields."""

    context_id: str = Field(default_factory=lambda: f"ctx_{uuid.uuid4().hex[:8]}")
    session_id: str = Field("sess_default")
    conversation_history: List[Dict[str, Any]] = Field(default_factory=list)
    memory_records: List[Dict[str, Any]] = Field(default_factory=list)
    desktop_context: Dict[str, Any] = Field(default_factory=dict)
    browser_state: Dict[str, Any] = Field(default_factory=dict)
    active_application: str = Field("desktop")
    clipboard: Optional[str] = Field(None)
    calendar_events: List[Dict[str, Any]] = Field(default_factory=list)
    current_mission: Optional[str] = Field(None)
    current_project: Optional[str] = Field(None)
    updated_at: float = Field(default_factory=time.time)


class SystemSnapshot(BaseModel):
    """System resource status snapshot."""

    cpu_percent: float = Field(0.0, description="Current CPU utilization percentage")
    ram_percent: float = Field(0.0, description="RAM utilization percentage")
    ram_used_mb: float = Field(0.0, description="RAM used in Megabytes")
    ram_total_mb: float = Field(0.0, description="Total RAM available in Megabytes")
    gpu_percent: float = Field(0.0, description="GPU utilization percentage")
    gpu_memory_mb: float = Field(0.0, description="GPU VRAM used in Megabytes")
    disk_percent: float = Field(0.0, description="Disk utilization percentage")
    battery_percent: float = Field(100.0, description="Battery state percentage")
    network_status: str = Field("ONLINE", description="Network status (ONLINE, OFFLINE, DEGRADED)")
    active_models: List[str] = Field(default_factory=list, description="Currently loaded AI models")
    active_missions_count: int = Field(0, description="Active missions count")
    running_agents_count: int = Field(0, description="Active running agents count")
    task_queue_length: int = Field(0, description="Tasks in kernel queue")
    timestamp: float = Field(default_factory=time.time)
    health_status: str = Field("HEALTHY", description="Overall health (HEALTHY, WARNING, CRITICAL)")


class EventRecord(BaseModel):
    """Structured kernel bus event."""

    event_id: str = Field(default_factory=lambda: f"evt_{uuid.uuid4().hex[:8]}")
    event_type: str = Field(..., description="Event name (e.g. MISSION_STARTED)")
    source: str = Field("kernel", description="Event emitter source")
    payload: Dict[str, Any] = Field(default_factory=dict, description="Event data body")
    timestamp: float = Field(default_factory=time.time)


class OSMemoryState(BaseModel):
    """In-memory state of AI OS Kernel."""

    current_tasks: List[Dict[str, Any]] = Field(default_factory=list)
    active_goals: List[Dict[str, Any]] = Field(default_factory=list)
    background_jobs: List[Dict[str, Any]] = Field(default_factory=list)
    recent_actions: List[Dict[str, Any]] = Field(default_factory=list)
    temporary_reasoning: List[str] = Field(default_factory=list)
    execution_stack: List[str] = Field(default_factory=list)


class IntentResponse(BaseModel):
    """Structured response returned by AI OS Kernel."""

    intent_id: str = Field(...)
    goal: str = Field(...)
    intent_type: str = Field(...)
    capability_match: Optional[CapabilityMatch] = Field(None)
    execution_plan: Optional[ExecutionPlan] = Field(None)
    status: str = Field("completed", description="Status (completed, failed, approval_required, processing)")
    result: Dict[str, Any] = Field(default_factory=dict, description="Execution payload output")
    verification: Optional[VerificationResult] = Field(None)
    voice_response: str = Field("", description="Natural spoken summary for voice-first response")
    latency_ms: float = Field(0.0)
    timestamp: float = Field(default_factory=time.time)


class KernelMetrics(BaseModel):
    """Telemetry collector metrics model."""

    total_intents_processed: int = Field(0)
    success_count: int = Field(0)
    failure_count: int = Field(0)
    average_latency_ms: float = Field(0.0)
    subsystem_invocations: Dict[str, int] = Field(default_factory=dict)
    voice_responses_count: int = Field(0)
    security_challenges_count: int = Field(0)
    timestamp: float = Field(default_factory=time.time)


class KernelHealth(BaseModel):
    """Health monitor status payload."""

    is_healthy: bool = Field(True)
    kernel_state: KernelState = Field(KernelState.IDLE)
    cpu_percent: float = Field(0.0)
    ram_percent: float = Field(0.0)
    active_subsystems: List[str] = Field(default_factory=list)
    event_bus_active: bool = Field(True)
    memory_health: str = Field("OK")
    timestamp: float = Field(default_factory=time.time)
