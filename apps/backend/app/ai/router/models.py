"""Domain models and schemas for the Intelligent AI Model Router.
"""

from enum import Enum
from typing import List, Optional, Any
import uuid
from pydantic import BaseModel, Field


class TaskType(str, Enum):
    """Supported task types matching agent actions prompts."""

    CODE_GENERATION = "CODE_GENERATION"
    DEBUGGING = "DEBUGGING"
    REFACTORING = "REFACTORING"
    RESEARCH = "RESEARCH"
    REASONING = "REASONING"
    CHAT = "CHAT"
    GENERAL_CHAT = "GENERAL_CHAT"
    SUMMARIZATION = "SUMMARIZATION"
    VISION = "VISION"
    EMBEDDING = "EMBEDDING"
    PLANNING = "PLANNING"
    SPEECH_TO_TEXT = "SPEECH_TO_TEXT"
    TEXT_TO_SPEECH = "TEXT_TO_SPEECH"


class RoutingRequest(BaseModel):
    """Input payload describing a task requiring model selection."""

    request_id: str = Field(default_factory=lambda: f"req_{uuid.uuid4().hex[:8]}")
    prompt: str
    task_type: Optional[TaskType] = Field(None, description="Pre-classified task type, if any.")
    priority: str = Field("medium", description="high, medium, low")
    context_size: int = Field(2048, description="Estimated inputs size in tokens.")


class ModelScore(BaseModel):
    """Represents performance metrics score calculated for a model option."""

    model_name: str
    capability_score: float = Field(0.0)
    latency_score: float = Field(0.0)
    resource_score: float = Field(0.0)
    final_score: float = Field(0.0)


class RoutingDecision(BaseModel):
    """The computed final model selected by the router pipeline."""

    selected_model: str
    provider: str
    reason: str
    fallback_chain: List[str] = Field(default_factory=list)
    confidence: float = Field(1.0)


class RoutingResult(BaseModel):
    """Final outcome summary generated by executing the routed model selection."""

    response: Any = Field(..., description="Response payload.")
